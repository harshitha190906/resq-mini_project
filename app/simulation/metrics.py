"""
ResQNet — app/simulation/metrics.py
===================================
Utility module that computes summary statistics from a
:class:`app.simulation.engine.SimulationEngine` run.

All calculations are **deterministic** and expressed in SI units:
* time – seconds (float)
* size – bytes (int)
* bandwidth – bits per second (float)
* delay – seconds (float)

The class is deliberately lightweight – it accepts the list of
:class:`app.simulation.engine.PacketEvent` objects generated by the engine
and provides ready‑to‑use properties.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import List, Optional

from app.simulation.engine import PacketEvent


@dataclass
class SimulationMetrics:
    """Collect and expose key performance indicators for a simulation run.

    The metrics are based on the raw ``PacketEvent`` records.  All timestamps
    are measured in **seconds**, packet size in **bytes**, and throughput is
    expressed in **bits per second**.
    """

    events: List[PacketEvent]

    # ---------------------------------------------------------------------
    # Helper properties
    # ---------------------------------------------------------------------
    @property
    def total_sent(self) -> int:
        """Total number of packets injected into the network."""
        return len(self.events)

    @property
    def total_delivered(self) -> int:
        """Number of packets that reached their destination successfully."""
        return sum(1 for ev in self.events if ev.delivered)

    @property
    def total_lost(self) -> int:
        """Number of packets that were not delivered (any loss reason)."""
        return self.total_sent - self.total_delivered

    @property
    def delivery_ratio(self) -> float:
        """Fraction of packets delivered (0.0 – 1.0)."""
        if self.total_sent == 0:
            return 0.0
        return self.total_delivered / self.total_sent

    @property
    def loss_ratio(self) -> float:
        """Fraction of packets lost (0.0 – 1.0)."""
        if self.total_sent == 0:
            return 0.0
        return self.total_lost / self.total_sent

    @property
    def total_bits_transmitted(self) -> int:
        """Sum of *size_bytes* × 8 for every packet (including lost ones)."""
        return sum(ev.size_bytes * 8 for ev in self.events)

    @property
    def simulation_duration(self) -> float:
        """Time between the first injection and the last recorded timestamp.

        If no packets were sent the duration is ``0.0``.
        """
        if not self.events:
            return 0.0
        first = min(ev.send_timestamp for ev in self.events)
        # Use arrival timestamp if delivered, otherwise the last hop timestamp
        last = max(
            ev.arrival_timestamp if ev.delivered else ev.timestamps[-1]
            for ev in self.events
        )
        return max(0.0, last - first)

    @property
    def throughput_bps(self) -> float:
        """Average throughput in **bits per second** over the whole run.

        Defined as ``total_bits_transmitted / simulation_duration``.  If the
        duration is zero the result is ``0.0``.
        """
        dur = self.simulation_duration
        return self.total_bits_transmitted / dur if dur > 0 else 0.0

    @property
    def average_end_to_end_delay(self) -> float:
        """Mean of (arrival – send) for successfully delivered packets.

        Returns ``0.0`` when there are no successful deliveries.
        """
        delivered = [ev for ev in self.events if ev.delivered]
        if not delivered:
            return 0.0
        total_delay = sum(ev.arrival_timestamp - ev.send_timestamp for ev in delivered)
        return total_delay / len(delivered)

    @property
    def total_retransmissions(self) -> int:
        """Sum of ``retransmissions`` across all packets (GBN only)."""
        return sum(ev.retransmissions for ev in self.events)

    @property
    def retransmission_rate(self) -> float:
        """Average number of retransmissions per packet (0.0 when none)."""
        if self.total_sent == 0:
            return 0.0
        return self.total_retransmissions / self.total_sent

    @property
    def avg_delay_ms(self) -> float:
        """Mean end-to-end delay in milliseconds for delivered packets."""
        return self.average_end_to_end_delay * 1000.0

    @property
    def throughput_kbps(self) -> float:
        """Average throughput in kilobits per second (kbps).

        Formula: (Total bits transmitted) / (Simulation duration in seconds) / 1000.0
        """
        return self.throughput_bps / 1000.0

    def time_series_data(self) -> dict:
        """Generate time-series telemetry records for dashboard charts.

        Returns
        -------
        dict
            Contains labels and data arrays for:
            - delivery: packet delivery progress over time
            - loss: packet loss events over time
            - delay_throughput: per-packet delay and cumulative throughput
        """
        if not self.events:
            return {
                "labels": [],
                "delivery_cumulative": [],
                "delivery_instant": [],
                "loss_cumulative": [],
                "loss_instant": [],
                "delay_ms": [],
                "throughput_kbps": [],
            }

        labels = []
        delivery_cum = []
        delivery_inst = []
        loss_cum = []
        loss_inst = []
        delays = []
        throughputs = []

        first_time = min(ev.send_timestamp for ev in self.events) if self.events else 0.0
        cum_del = 0
        cum_lost = 0
        cum_bits = 0

        for i, ev in enumerate(self.events, start=1):
            t_rel = round(max(0.0, ev.send_timestamp - first_time), 2)
            labels.append(f"Pkt {ev.packet_id} ({t_rel}s)")

            if ev.delivered:
                cum_del += 1
                delivery_inst.append(1)
                loss_inst.append(0)
                # End-to-end delay in milliseconds
                delay = round((ev.arrival_timestamp - ev.send_timestamp) * 1000.0, 2) if ev.arrival_timestamp is not None else 0.0
                delays.append(delay)
            else:
                cum_lost += 1
                delivery_inst.append(0)
                loss_inst.append(1)
                delays.append(0.0)

            delivery_cum.append(cum_del)
            loss_cum.append(cum_lost)

            cum_bits += ev.size_bytes * 8
            # Running duration up to this event's latest timestamp
            last_ts = ev.arrival_timestamp if ev.delivered else (ev.timestamps[-1] if ev.timestamps else ev.send_timestamp)
            dur_so_far = max(0.001, (last_ts or ev.send_timestamp) - first_time)
            cur_throughput = round((cum_bits / dur_so_far) / 1000.0, 2)
            throughputs.append(cur_throughput)

        return {
            "labels": labels,
            "delivery_cumulative": delivery_cum,
            "delivery_instant": delivery_inst,
            "loss_cumulative": loss_cum,
            "loss_instant": loss_inst,
            "delay_ms": delays,
            "throughput_kbps": throughputs,
        }

    # ---------------------------------------------------------------------
    # Pretty‑print helper used by tests for debugging
    # ---------------------------------------------------------------------
    def as_dict(self) -> dict:
        """Return a plain ``dict`` representation – convenient for asserts and JSON API."""
        return {
            "sent":                  self.total_sent,
            "total_sent":            self.total_sent,
            "delivered":             self.total_delivered,
            "total_delivered":       self.total_delivered,
            "lost":                  self.total_lost,
            "total_lost":            self.total_lost,
            "delivery_ratio":        self.delivery_ratio,
            "loss_ratio":            self.loss_ratio,
            "throughput_bps":        self.throughput_bps,
            "throughput_kbps":       round(self.throughput_kbps, 2),
            "avg_delay_s":           self.average_end_to_end_delay,
            "avg_delay_ms":          round(self.avg_delay_ms, 2),
            "retransmissions":       self.total_retransmissions,
            "total_retransmissions": self.total_retransmissions,
            "retransmission_rate":   self.retransmission_rate,
            "duration_s":            round(self.simulation_duration, 3),
            "has_data":              len(self.events) > 0,
            "time_series":           self.time_series_data(),
        }

"""End of metrics module."""
